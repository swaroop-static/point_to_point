import type { ImageEntry, PolygonGeom, Project } from '../core/types';
import type { ZipEntry } from './zip';

/**
 * YOLO dataset export (Ultralytics-style folder layout).
 *
 *   data.yaml
 *   images/<stem>.<ext>      (only when the original file bytes are in memory)
 *   labels/<stem>.txt
 *
 * Modes:
 *   detect  - one line per box or polygon: "<cls> <cx> <cy> <w> <h>" (polygons
 *             use their axis-aligned bounds).
 *   segment - one line per polygon or box: "<cls> x1 y1 x2 y2 ..." (boxes
 *             become 4-corner polygons).
 * Coordinates are normalized to 0..1 by the original image size. Class index
 * is the 0-based position in the project's class list. Polylines and
 * keypoints have no standard YOLO detect/segment representation and are
 * skipped with a warning (they stay in the project file).
 *
 * There is no train/val split: data.yaml points both at images/ and the
 * docs say so; split the folder yourself if you need a held-out set.
 */

export type YoloMode = 'detect' | 'segment';

export interface YoloResult {
  entries: ZipEntry[];
  warnings: string[];
  labelCount: number;
}

export function exportYolo(
  project: Project,
  mode: YoloMode,
  getImageBytes: (img: ImageEntry) => Promise<Uint8Array | null>,
): Promise<YoloResult> {
  return build(project, mode, getImageBytes);
}

async function build(
  project: Project,
  mode: YoloMode,
  getImageBytes: (img: ImageEntry) => Promise<Uint8Array | null>,
): Promise<YoloResult> {
  const enc = new TextEncoder();
  const warnings: string[] = [];
  const entries: ZipEntry[] = [];
  const classIndex = new Map(project.classes.map((c, i) => [c.id, i]));
  const usedStems = new Set<string>();
  const skipped = new Set<string>();
  let labelCount = 0;
  let missingImages = 0;

  for (const img of project.images) {
    const { stem, ext } = splitName(img.name);
    let unique = stem, n = 2;
    while (usedStems.has(unique.toLowerCase())) unique = `${stem}_${n++}`;
    usedStems.add(unique.toLowerCase());

    const lines: string[] = [];
    for (const a of img.annotations) {
      const ci = classIndex.get(a.classId);
      if (ci === undefined) { warnings.push(`Image "${img.name}": annotation with unknown class skipped.`); continue; }
      const g = a.geom;
      if (g.kind === 'polyline' || g.kind === 'keypoint') { skipped.add(g.kind); continue; }

      if (g.kind === 'box') {
        const b = clampBox(g.x, g.y, g.w, g.h, img);
        if (b.w <= 0 || b.h <= 0) { warnings.push(`Image "${img.name}": zero-area box skipped.`); continue; }
        if (mode === 'detect') {
          lines.push(`${ci} ${fmt((b.x + b.w / 2) / img.width)} ${fmt((b.y + b.h / 2) / img.height)} ${fmt(b.w / img.width)} ${fmt(b.h / img.height)}`);
        } else {
          const c = [[b.x, b.y], [b.x + b.w, b.y], [b.x + b.w, b.y + b.h], [b.x, b.y + b.h]];
          lines.push(`${ci} ${c.map(([x, y]) => `${fmt(x / img.width)} ${fmt(y / img.height)}`).join(' ')}`);
        }
      } else {
        const pts = clampPoly(g, img);
        if (polygonArea(pts) <= 0) { warnings.push(`Image "${img.name}": zero-area polygon skipped.`); continue; }
        if (mode === 'detect') {
          const xs = pts.map((p) => p.x), ys = pts.map((p) => p.y);
          const x1 = Math.min(...xs), x2 = Math.max(...xs), y1 = Math.min(...ys), y2 = Math.max(...ys);
          lines.push(`${ci} ${fmt((x1 + x2) / 2 / img.width)} ${fmt((y1 + y2) / 2 / img.height)} ${fmt((x2 - x1) / img.width)} ${fmt((y2 - y1) / img.height)}`);
        } else {
          lines.push(`${ci} ${pts.map((p) => `${fmt(p.x / img.width)} ${fmt(p.y / img.height)}`).join(' ')}`);
        }
      }
    }
    labelCount += lines.length;
    entries.push({ name: `labels/${unique}.txt`, data: enc.encode(lines.length ? lines.join('\n') + '\n' : '') });

    const bytes = await getImageBytes(img);
    if (bytes) entries.push({ name: `images/${unique}${ext}`, data: bytes });
    else missingImages += 1;
  }

  for (const k of skipped) {
    warnings.push(`${k} annotations have no YOLO ${mode} representation and were skipped. They are kept in the project file.`);
  }
  if (missingImages) {
    warnings.push(`${missingImages} image file${missingImages === 1 ? ' is' : 's are'} not loaded, so only labels were written for ${missingImages === 1 ? 'it' : 'them'}.`);
  }

  const names = project.classes.map((c, i) => `  ${i}: ${yamlString(c.name)}`).join('\n');
  const yaml = `# Generated by Annotate Anything (${mode}). No train/val split: both point at images/.\npath: .\ntrain: images\nval: images\nnames:\n${names}\n`;
  entries.unshift({ name: 'data.yaml', data: enc.encode(yaml) });

  return { entries, warnings, labelCount };
}

function splitName(name: string): { stem: string; ext: string } {
  const dot = name.lastIndexOf('.');
  const rawStem = dot > 0 ? name.slice(0, dot) : name;
  const ext = dot > 0 ? name.slice(dot).toLowerCase().replace(/[^.a-z0-9]/g, '') : '';
  const stem = rawStem.replace(/[^A-Za-z0-9._-]+/g, '_').replace(/^\.+/, '') || 'image';
  return { stem, ext };
}

function clampBox(x: number, y: number, w: number, h: number, img: ImageEntry) {
  const x1 = Math.max(0, Math.min(x, x + w)), x2 = Math.min(img.width, Math.max(x, x + w));
  const y1 = Math.max(0, Math.min(y, y + h)), y2 = Math.min(img.height, Math.max(y, y + h));
  return { x: x1, y: y1, w: Math.max(0, x2 - x1), h: Math.max(0, y2 - y1) };
}

function clampPoly(g: PolygonGeom, img: ImageEntry) {
  return g.points.map((p) => ({ x: Math.max(0, Math.min(img.width, p.x)), y: Math.max(0, Math.min(img.height, p.y)) }));
}

function polygonArea(pts: { x: number; y: number }[]): number {
  let a = 0;
  for (let i = 0; i < pts.length; i++) {
    const j = (i + 1) % pts.length;
    a += pts[i].x * pts[j].y - pts[j].x * pts[i].y;
  }
  return Math.abs(a) / 2;
}

function fmt(n: number): string {
  const v = Math.max(0, Math.min(1, n));
  return v.toFixed(6).replace(/0+$/, '').replace(/\.$/, '') || '0';
}

function yamlString(s: string): string {
  return /^[A-Za-z0-9_][A-Za-z0-9_ -]*$/.test(s) && !/^(true|false|null|yes|no|on|off|~|\d+)$/i.test(s.trim())
    ? s
    : JSON.stringify(s);
}
